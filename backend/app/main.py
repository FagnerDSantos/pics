from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from app.api.v1.router import api_router
from app.core.config import get_settings
from app.core.errors import register_exception_handlers
from app.middleware.body_limit import RequestBodyLimitMiddleware
from app.middleware.security_headers import SecurityHeadersMiddleware

settings = get_settings()

api = FastAPI(
    title="Pics API",
    description="API do projeto Pics.",
    version=settings.app_version,
)

register_exception_handlers(api)
api.include_router(api_router)

cors_api = CORSMiddleware(
    api,
    allow_origins=settings.cors_origins,
    allow_credentials=True,
    allow_methods=["GET", "POST", "PUT", "PATCH", "DELETE"],
    allow_headers=["Authorization", "Content-Type"],
)

# Keep security headers on responses generated by Starlette's outer error handler too.
app = SecurityHeadersMiddleware(RequestBodyLimitMiddleware(cors_api))
